"""Where the dashboard reads its data: the PostgreSQL database, or the demo files.

DASHBOARD_DEMO=1 switches to dashboard/demo/ (generated by scripts/make_demo_data.py).
The public demo on GitHub Pages runs this way, so no scraped data is ever published.
"""
from __future__ import annotations

import json
import os
import sys
from decimal import Decimal
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
DEMO = bool(os.getenv("DASHBOARD_DEMO"))


class Postgres:
    def __init__(self):
        sys.path.insert(0, str(HERE.parent))
        from tracker.config import settings
        from tracker.db import connect, read_sql
        self._connect, self._read_sql = connect, read_sql
        self.sites = {k: v["name"] for k, v in settings.load_sites().items()}

    def q(self, sql: str, params: tuple | None = None) -> pd.DataFrame:
        with self._connect() as conn:
            df = self._read_sql(conn, sql, params)
        # Postgres NUMERIC arrives as Decimal; charts want floats.
        for col in df.columns:
            if df[col].map(lambda v: isinstance(v, Decimal)).any():
                df[col] = pd.to_numeric(df[col])
        return df

    def runs(self) -> pd.DataFrame:
        return self.q("SELECT id, started_at, finished_at, status, products_seen, pages_fetched, errors, report "
                      "FROM runs WHERE status <> 'running' ORDER BY id DESC LIMIT 60")

    def latest(self, run_id: int) -> pd.DataFrame:
        return self.q("SELECT * FROM latest_prices WHERE run_id = %s", (run_id,))

    def drops(self) -> pd.DataFrame:
        return self.q("""SELECT p.site, p.name, a.old_price, a.new_price, a.drop_pct, p.url, r.started_at
                         FROM alerts a JOIN products p ON p.id = a.product_id JOIN runs r ON r.id = a.run_id
                         ORDER BY r.started_at DESC, a.drop_pct DESC LIMIT 200""")

    def history(self, group_id: int) -> pd.DataFrame:
        return self.q("""SELECT p.site, s.scraped_at, COALESCE(s.promo_price, s.price) AS prix, s.price AS prix_normal
                         FROM price_snapshots s JOIN products p ON p.id = s.product_id
                         WHERE p.group_id = %s ORDER BY s.scraped_at""", (group_id,))


class Demo:
    """Same tables as the database, read from CSV/JSON with pandas."""

    def __init__(self, folder: Path = HERE / "demo"):
        self.sites = json.loads((folder / "sites.json").read_text(encoding="utf-8"))
        self._runs = pd.DataFrame(json.loads((folder / "runs.json").read_text(encoding="utf-8")))
        for col in ("started_at", "finished_at"):
            self._runs[col] = pd.to_datetime(self._runs[col], utc=True)
        self.products = pd.read_csv(folder / "products.csv", dtype={"group_id": "Int64"})
        snaps = pd.read_csv(folder / "snapshots.csv")
        snaps = snaps.merge(self._runs[["id", "started_at"]].rename(columns={"id": "run_id", "started_at": "scraped_at"}),
                            on="run_id")
        snaps["effective_price"] = snaps["promo_price"].fillna(snaps["price"])
        self.snaps = snaps
        self.alerts = pd.read_csv(folder / "alerts.csv")

    def runs(self) -> pd.DataFrame:
        return self._runs.sort_values("id", ascending=False).reset_index(drop=True)

    def latest(self, run_id: int) -> pd.DataFrame:
        return self.snaps[self.snaps["run_id"] == run_id].merge(
            self.products, left_on="product_id", right_on="id").reset_index(drop=True)

    def drops(self) -> pd.DataFrame:
        d = (self.alerts.merge(self.products, left_on="product_id", right_on="id")
             .merge(self._runs[["id", "started_at"]], left_on="run_id", right_on="id"))
        return (d.sort_values(["started_at", "drop_pct"], ascending=False)
                [["site", "name", "old_price", "new_price", "drop_pct", "url", "started_at"]].head(200)
                .reset_index(drop=True))

    def history(self, group_id: int) -> pd.DataFrame:
        h = self.snaps.merge(self.products[self.products["group_id"] == group_id], left_on="product_id", right_on="id")
        return (h.assign(prix=h["effective_price"], prix_normal=h["price"])
                [["site", "scraped_at", "prix", "prix_normal"]].sort_values("scraped_at").reset_index(drop=True))


def open_source():
    return Demo() if DEMO else Postgres()
